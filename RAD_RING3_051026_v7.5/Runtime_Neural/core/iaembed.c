#define VOCAB_TAM (sizeof(VOCAB) / sizeof(VOCAB[0]))

static float emb_raiz(float x) {
    if (x <= 0.0f) return 0.0f;
    float r = x;
    for (int i = 0; i < 25; i++) r = 0.5f * (r + x / r);
    return r;
}

int iaembed_palavra(const char* palavra, float* out_vec) {
    if (!palavra || !out_vec) return 0;
    for (size_t i = 0; i < VOCAB_TAM; i++) {
        if (strcmp(palavra, VOCAB[i].palavra) == 0) {
            for (int d = 0; d < EMB_DIM; d++) out_vec[d] = VOCAB[i].v[d];
            return 1;
        }
    }
    return 0;
}

