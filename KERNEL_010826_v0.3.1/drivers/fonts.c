void font_init(void) {
    for (int i = 0; i < 256; i++) {
        int vazio = 1;
        for (int j = 0; j < 8; j++) {
            if (font_8x8[i][j] != 0) {
                vazio = 0;
                break;
            }
        }
        if (vazio && i != ' ') {
            for (int j = 0; j < 8; j++) {
                font_8x8[i][j] = font_8x8['?'][j];
            }
        }
    }
}
